#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ThemeAppearance {
    Light,
    Dark,
}

impl ThemeAppearance {
    pub fn is_dark(self) -> bool {
        matches!(self, Self::Dark)
    }
}

macro_rules! theme_colors {
    ($($role:ident),* $(,)?) => {
        /// Product roles shared by web CSS, React Native tokens, and native surfaces.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub struct ThemeColors {
            $(pub $role: &'static str,)*
        }

        /// `THEME_COLOR_ROLES`, in upstream order.
        pub const THEME_COLOR_ROLES: &[&str] = &[$(stringify!($role)),*];

        impl ThemeColors {
            /// Every `(role, value)` pair, in upstream order.
            pub fn entries(&self) -> Vec<(&'static str, &'static str)> {
                vec![$((stringify!($role), self.$role)),*]
            }
        }
    };
}

